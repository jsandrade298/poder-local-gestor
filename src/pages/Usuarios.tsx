import { useState, useMemo } from "react";
import { useNavigate } from "react-router-dom";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { ErrorState } from "@/components/ui/ErrorState";
import { supabase } from "@/integrations/supabase/client";
import { Card, CardHeader, CardTitle, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Plus, Search, MoreHorizontal, Mail, Phone, Shield, UserCheck } from "lucide-react";
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuTrigger } from "@/components/ui/dropdown-menu";
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogTrigger, DialogFooter } from "@/components/ui/dialog";
import { AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent, AlertDialogDescription, AlertDialogFooter, AlertDialogHeader, AlertDialogTitle, AlertDialogTrigger } from "@/components/ui/alert-dialog";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { toast } from "@/hooks/use-toast";
import { useAuth } from "@/contexts/AuthContext";
import { formatDateTime } from '@/lib/dateUtils';
import { SaidaUsuarioDialog, reativarUsuario } from '@/components/forms/SaidaUsuarioDialog';

export default function Usuarios() {
  const { user } = useAuth();
  const [searchTerm, setSearchTerm] = useState("");
  const [isCreateDialogOpen, setIsCreateDialogOpen] = useState(false);
  const [isViewDialogOpen, setIsViewDialogOpen] = useState(false);
  const [isEditDialogOpen, setIsEditDialogOpen] = useState(false);
  const [isResetPasswordDialogOpen, setIsResetPasswordDialogOpen] = useState(false);
  const [selectedUser, setSelectedUser] = useState<any>(null);
  const [editingUser, setEditingUser] = useState<any>(null);
  const [resetPasswordUser, setResetPasswordUser] = useState<any>(null);
  const [newPassword, setNewPassword] = useState("");
  const [newUser, setNewUser] = useState({
    nome: "",
    email: "",
    senha: "",
    telefone: "",
    cargo: "",
    ativo: true
  });
  const queryClient = useQueryClient();
  const navigate = useNavigate();

  // Fetch users with their roles and demandas count
  const { data: usuarios = [], isLoading: isLoadingUsuarios, isError: isErrorUsuarios, refetch: refetchUsuarios } = useQuery({
    queryKey: ['usuarios'],
    queryFn: async () => {
      // Fetch profiles
      const { data: profilesData, error: profilesError } = await supabase
        .from('profiles')
        .select('*');

      if (profilesError) throw profilesError;

      // Fetch all user roles
      const { data: rolesData, error: rolesError } = await supabase
        .from('user_roles')
        .select('user_id, role');

      if (rolesError) throw rolesError;

      // Fetch demandas count for each user
      const { data: demandasData, error: demandasError } = await supabase
        .from('demandas')
        .select('criado_por, responsavel_id');

      if (demandasError) {
        console.error('Erro ao buscar demandas:', demandasError);
        throw demandasError;
      }

      // Create roles map
      const rolesMap = rolesData.reduce((acc, roleItem) => {
        acc[roleItem.user_id] = roleItem.role;
        return acc;
      }, {});

      // Count demandas by user
      const demandasCount = demandasData?.reduce((acc, demanda) => {
        if (demanda.criado_por) {
          acc[demanda.criado_por] = (acc[demanda.criado_por] || 0) + 1;
        }
        if (demanda.responsavel_id && demanda.responsavel_id !== demanda.criado_por) {
          acc[demanda.responsavel_id] = (acc[demanda.responsavel_id] || 0) + 1;
        }
        return acc;
      }, {}) || {};

      // Combine profiles with roles and demandas count
      return profilesData.map(profile => ({
        ...profile,
        total_demandas: demandasCount[profile.id] || 0,
        role: rolesMap[profile.id] || 'usuario',
        ativo: (profile as any).ativo !== false
      }));
    }
  });

  // Create user mutation
  const createUserMutation = useMutation({
    mutationFn: async (userData: typeof newUser) => {
      if (!userData.senha || userData.senha.length < 6) {
        throw new Error("A senha deve ter pelo menos 6 caracteres");
      }

      // Usar Edge Function para criar usuário sem validação de domínio
      const { data, error } = await supabase.functions.invoke('create-user-custom', {
        body: {
          email: userData.email,
          password: userData.senha,
          nome: userData.nome,
          telefone: userData.telefone,
          cargo: userData.cargo
        }
      });

      if (error) {
        console.error('Erro na função create-user-custom:', error);
        throw error;
      }

      if (!data.success) {
        throw new Error(data.error || 'Erro ao criar usuário');
      }

      return data;
    },
    onSuccess: () => {
      // Forçar recarregamento imediato dos dados
      queryClient.invalidateQueries({ queryKey: ['usuarios'] });
      toast({
        title: "Usuário criado",
        description: "O usuário foi criado com sucesso e já pode fazer login no sistema.",
      });
      setIsCreateDialogOpen(false);
      setNewUser({ nome: "", email: "", senha: "", telefone: "", cargo: "", ativo: true });
    },
    onError: (error) => {
      console.error("Erro ao criar usuário:", error);
      toast({
        title: "Erro ao criar usuário",
        description: error.message || "Verifique se o email não está em uso.",
        variant: "destructive",
      });
    }
  });

  // Update user mutation
  const updateUserMutation = useMutation({
    mutationFn: async ({ id, updates }: { id: string; updates: any }) => {
      console.log('🔄 MUTATION - ID do usuário:', id);
      console.log('🔄 MUTATION - Updates:', updates);
      
      const { data, error, count } = await supabase
        .from('profiles')
        .update(updates)
        .eq('id', id)
        .select();
      
      console.log('🔄 MUTATION - Resultado data:', data);
      console.log('🔄 MUTATION - Resultado error:', error);
      console.log('🔄 MUTATION - Count afetados:', count);
      
      if (error) throw error;
      return { success: true };
    },
    onSuccess: async () => {
      // Aguardar um pouco e depois forçar recarregamento
      await new Promise(resolve => setTimeout(resolve, 500));
      
      // Invalidar cache primeiro
      queryClient.invalidateQueries({ queryKey: ['usuarios'] });
      
      // Então forçar refetch
      await refetchUsuarios();
      
      toast({
        title: "Usuário atualizado",
        description: "O usuário foi atualizado com sucesso.",
      });
      setIsEditDialogOpen(false);
      setEditingUser(null);
    },
    onError: (error) => {
      toast({
        title: "Erro",
        description: "Erro ao atualizar usuário: " + error.message,
        variant: "destructive",
      });
    }
  });

  // Update user role mutation
  const updateRoleMutation = useMutation({
    mutationFn: async ({ userId, role }: { userId: string; role: string }) => {
      const { error } = await supabase
        .from('user_roles')
        .update({ role })
        .eq('user_id', userId);
      
      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['usuarios'] });
      toast({
        title: "Papel atualizado",
        description: "O papel do usuário foi atualizado com sucesso.",
      });
    },
    onError: (error) => {
      toast({
        title: "Erro",
        description: "Erro ao atualizar papel: " + error.message,
        variant: "destructive",
      });
    }
  });

  // Reset password mutation
  const resetPasswordMutation = useMutation({
    mutationFn: async ({ userId, newPassword }: { userId: string; newPassword: string }) => {
      console.log('🔄 RESET - Iniciando reset para userId:', userId);
      
      const { data, error } = await supabase.functions.invoke('reset-password', {
        body: { 
          userId, 
          newPassword 
        }
      });

      if (error) {
        console.error('❌ RESET - Erro na função:', error);
        throw error;
      }

      if (!data.success) {
        console.error('❌ RESET - Falha na resposta:', data);
        throw new Error(data.error || 'Erro ao resetar senha');
      }

      console.log('✅ RESET - Sucesso:', data);
      return data;
    },
    onSuccess: (data) => {
      queryClient.invalidateQueries({ queryKey: ['usuarios'] });
      toast({
        title: "Senha alterada com sucesso",
        description: `A senha do usuário ${resetPasswordUser?.nome} foi alterada. O usuário já pode fazer login com a nova senha.`,
      });
      setIsResetPasswordDialogOpen(false);
      setNewPassword("");
      setResetPasswordUser(null);
    },
    onError: (error) => {
      console.error("Erro no reset de senha:", error);
      toast({
        title: "Erro ao alterar senha",
        description: error.message || "Tente novamente em alguns minutos.",
        variant: "destructive",
      });
    }
  });

  const filteredUsuarios = useMemo(() => {
    return usuarios.filter(usuario => {
      return usuario.nome.toLowerCase().includes(searchTerm.toLowerCase()) ||
             usuario.email.toLowerCase().includes(searchTerm.toLowerCase());
    });
  }, [usuarios, searchTerm]);

  const handleCreateUser = () => {
    if (!newUser.nome.trim() || !newUser.email.trim() || !newUser.senha.trim()) return;
    
    createUserMutation.mutate(newUser);
  };

  const handleViewProfile = (usuario: any) => {
    setSelectedUser(usuario);
    setIsViewDialogOpen(true);
  };

  const handleEditUser = (usuario: any) => {
    setEditingUser({ ...usuario });
    setIsEditDialogOpen(true);
  };

  const handleUpdateUser = () => {
    if (!editingUser) return;
    
    console.log('👤 Usuário sendo editado (completo):', editingUser);
    
    // Enviar apenas os campos que podem ser atualizados
    const updates = {
      nome: editingUser.nome,
      email: editingUser.email,
      telefone: editingUser.telefone,
      cargo: editingUser.cargo
    };
    
    console.log('📝 Updates específicos sendo enviados:', updates);
    updateUserMutation.mutate({ id: editingUser.id, updates });
  };

  const handleUpdateRole = (userId: string, newRole: string) => {
    updateRoleMutation.mutate({ userId, role: newRole });
  };

  const handleViewUserDemandas = (userId: string, userName: string) => {
    navigate(`/demandas?responsavel=${userId}&responsavelNome=${encodeURIComponent(userName)}`);
  };

  const handleResetPassword = (user: any) => {
    setResetPasswordUser(user);
    setIsResetPasswordDialogOpen(true);
  };

  const handleConfirmResetPassword = () => {
    if (!resetPasswordUser || !newPassword) return;
    
    resetPasswordMutation.mutate({ 
      userId: resetPasswordUser.id, 
      newPassword 
    });
  };

  // Saída de usuário (desativar ou transferir e excluir) — modal próprio
  const [usuarioSaindo, setUsuarioSaindo] = useState<any>(null);
  const reativar = useMutation({
    mutationFn: (id: string) => reativarUsuario(id),
    onSuccess: () => { queryClient.invalidateQueries({ queryKey: ['usuarios'] }); toast({ title: "Acesso reativado" }); },
    onError: (e: any) => toast({ title: "Não foi possível reativar", description: e.message, variant: "destructive" }),
  });


  if (isErrorUsuarios) {
    return <ErrorState what="os usuários" onRetry={() => refetchUsuarios()} />;
  }

  if (isLoadingUsuarios) {
    return (
      <div className="space-y-6">
        <div className="flex items-center justify-center h-64">
          <div className="text-center">
            <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-primary mx-auto"></div>
            <p className="text-muted-foreground mt-2">Carregando usuários...</p>
          </div>
        </div>
      </div>
    );
  }


  const papelDo = (u: any) => (u.role === 'admin' ? 'Admin' : u.role === 'gestor' ? 'Gestor' : u.role === 'atendente' ? 'Atendente' : 'Usuário');

  // Menu ⋯ de cada usuário (tabela no computador, cartões no celular)
  const acoesDoUsuario = (usuario: any) => (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button variant="ghost" className="h-8 w-8 p-0">
          <MoreHorizontal className="h-4 w-4" />
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end">
        <DropdownMenuItem onClick={() => handleViewProfile(usuario)}>
          Ver Perfil
        </DropdownMenuItem>
        <DropdownMenuItem onClick={() => handleEditUser(usuario)}>
          Editar
        </DropdownMenuItem>
        <DropdownMenuItem onClick={() => handleViewUserDemandas(usuario.id, usuario.nome)}>
          Ver Demandas
        </DropdownMenuItem>
         <DropdownMenuItem onClick={() => handleResetPassword(usuario)}>
           Reset Senha
         </DropdownMenuItem>
        {usuario.ativo ? (
          <DropdownMenuItem className="text-destructive focus:text-destructive" onSelect={() => setUsuarioSaindo(usuario)}>
            Desativar ou excluir…
          </DropdownMenuItem>
        ) : (
          <>
            <DropdownMenuItem onSelect={() => reativar.mutate(usuario.id)}>Reativar acesso</DropdownMenuItem>
            <DropdownMenuItem className="text-destructive focus:text-destructive" onSelect={() => setUsuarioSaindo(usuario)}>
              Excluir…
            </DropdownMenuItem>
          </>
        )}
      </DropdownMenuContent>
    </DropdownMenu>
  );

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-foreground">
            Gestão de Usuários
          </h1>
          <p className="text-muted-foreground">
            Gerencie os usuários do sistema
          </p>
        </div>
        
        <Dialog open={isCreateDialogOpen} onOpenChange={setIsCreateDialogOpen}>
          <DialogTrigger asChild>
            <Button>
              <Plus className="h-4 w-4 mr-2" />
              Novo Usuário
            </Button>
          </DialogTrigger>
          <DialogContent>
            <DialogHeader>
              <DialogTitle>Criar Novo Usuário</DialogTitle>
            </DialogHeader>
            <div className="space-y-4">
              <div className="space-y-2">
                <Label htmlFor="nome">Nome Completo</Label>
                <Input
                  id="nome"
                  placeholder="Nome do usuário"
                  value={newUser.nome}
                  onChange={(e) => setNewUser({ ...newUser, nome: e.target.value })}
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="email">Email</Label>
                <Input
                  id="email"
                  type="email"
                  placeholder="usuario@gabinete.gov.br"
                  value={newUser.email}
                  onChange={(e) => setNewUser({ ...newUser, email: e.target.value })}
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="senha">Senha</Label>
                <Input
                  id="senha"
                  type="password"
                  placeholder="Senha do usuário (mínimo 6 caracteres)"
                  value={newUser.senha}
                  onChange={(e) => setNewUser({ ...newUser, senha: e.target.value })}
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="telefone">Telefone</Label>
                <Input
                  id="telefone"
                  placeholder="(11) 99999-9999"
                  value={newUser.telefone}
                  onChange={(e) => setNewUser({ ...newUser, telefone: e.target.value })}
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="cargo">Cargo</Label>
                <Input
                  id="cargo"
                  placeholder="Ex: Analista, Coordenador..."
                  value={newUser.cargo}
                  onChange={(e) => setNewUser({ ...newUser, cargo: e.target.value })}
                />
              </div>
              <div className="flex items-center space-x-2">
                <Switch
                  id="ativo"
                  checked={newUser.ativo}
                  onCheckedChange={(checked) => setNewUser({ ...newUser, ativo: checked })}
                />
                <Label htmlFor="ativo">Usuário ativo</Label>
              </div>
            </div>
            <DialogFooter>
              <Button variant="outline" onClick={() => setIsCreateDialogOpen(false)}>
                Cancelar
              </Button>
              <Button 
                onClick={handleCreateUser} 
                disabled={!newUser.nome.trim() || !newUser.email.trim() || !newUser.senha.trim() || createUserMutation.isPending}
              >
                {createUserMutation.isPending ? "Criando..." : "Criar Usuário"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Dialog de Visualização de Perfil */}
        <Dialog open={isViewDialogOpen} onOpenChange={setIsViewDialogOpen}>
          <DialogContent className="max-w-md">
            <DialogHeader>
              <DialogTitle>Perfil do Usuário</DialogTitle>
            </DialogHeader>
            {selectedUser && (
              <div className="space-y-4">
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Nome</Label>
                  <p className="text-sm text-muted-foreground">{selectedUser.nome}</p>
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Email</Label>
                  <p className="text-sm text-muted-foreground">{selectedUser.email}</p>
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Telefone</Label>
                  <p className="text-sm text-muted-foreground">{selectedUser.telefone || "Não informado"}</p>
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Cargo</Label>
                  <p className="text-sm text-muted-foreground">{selectedUser.cargo || "Não informado"}</p>
                </div>
                <div className="space-y-3">
                  <Label className="text-sm font-medium">Papel</Label>
                  <div>
                    <Badge variant={
                      selectedUser.role === 'admin' ? 'destructive' : 
                      selectedUser.role === 'gestor' ? 'default' : 
                      selectedUser.role === 'atendente' ? 'secondary' : 'outline'
                    }>
                      {selectedUser.role === 'admin' ? 'Admin' : 
                       selectedUser.role === 'gestor' ? 'Gestor' :
                       selectedUser.role === 'atendente' ? 'Atendente' : 'Usuário'}
                    </Badge>
                  </div>
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Total de Demandas</Label>
                  <p className="text-sm text-muted-foreground">{selectedUser.total_demandas}</p>
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Data de Cadastro</Label>
                  <p className="text-sm text-muted-foreground">{formatDateTime(selectedUser.created_at).split(' ')[0]}</p>
                </div>
              </div>
            )}
            <DialogFooter>
              <Button variant="outline" onClick={() => setIsViewDialogOpen(false)}>
                Fechar
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Dialog de Edição */}
        <Dialog open={isEditDialogOpen} onOpenChange={setIsEditDialogOpen}>
          <DialogContent>
            <DialogHeader>
              <DialogTitle>Editar Usuário</DialogTitle>
            </DialogHeader>
            {editingUser && (
              <div className="space-y-4">
                <div className="space-y-2">
                  <Label htmlFor="edit-nome">Nome Completo</Label>
                  <Input
                    id="edit-nome"
                    value={editingUser.nome}
                    onChange={(e) => setEditingUser({ ...editingUser, nome: e.target.value })}
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="edit-email">Email</Label>
                  <Input
                    id="edit-email"
                    type="email"
                    value={editingUser.email}
                    onChange={(e) => setEditingUser({ ...editingUser, email: e.target.value })}
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="edit-telefone">Telefone</Label>
                  <Input
                    id="edit-telefone"
                    value={editingUser.telefone || ""}
                    onChange={(e) => setEditingUser({ ...editingUser, telefone: e.target.value })}
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="edit-cargo">Cargo</Label>
                  <Input
                    id="edit-cargo"
                    value={editingUser.cargo || ""}
                    onChange={(e) => setEditingUser({ ...editingUser, cargo: e.target.value })}
                  />
                </div>
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Papel do Usuário</Label>
                  <div className="p-2 bg-muted rounded-md">
                    <Badge variant="destructive">Admin</Badge>
                    <p className="text-xs text-muted-foreground mt-1">Todos os usuários têm acesso administrativo completo</p>
                  </div>
                </div>
              </div>
            )}
            <DialogFooter>
              <Button variant="outline" onClick={() => setIsEditDialogOpen(false)}>
                Cancelar
              </Button>
              <Button 
                onClick={handleUpdateUser} 
                disabled={updateUserMutation.isPending}
              >
                {updateUserMutation.isPending ? "Salvando..." : "Salvar Alterações"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Dialog de Reset de Senha */}
        <Dialog open={isResetPasswordDialogOpen} onOpenChange={setIsResetPasswordDialogOpen}>
          <DialogContent>
            <DialogHeader>
              <DialogTitle>Reset de Senha</DialogTitle>
            </DialogHeader>
            {resetPasswordUser && (
              <div className="space-y-4">
                <div className="space-y-2">
                  <Label className="text-sm font-medium">Usuário</Label>
                  <p className="text-sm text-muted-foreground">{resetPasswordUser.nome} - {resetPasswordUser.email}</p>
                </div>
                <div className="space-y-2">
                  <Label htmlFor="new-password">Nova Senha</Label>
                  <Input
                    id="new-password"
                    type="password"
                    placeholder="Digite a nova senha (mínimo 6 caracteres)"
                    value={newPassword}
                    onChange={(e) => setNewPassword(e.target.value)}
                  />
                </div>
                <div className="text-sm text-muted-foreground">
                  A nova senha será definida diretamente no sistema. O usuário poderá fazer login imediatamente com esta senha.
                </div>
              </div>
            )}
            <DialogFooter>
              <Button variant="outline" onClick={() => {
                setIsResetPasswordDialogOpen(false);
                setNewPassword("");
                setResetPasswordUser(null);
              }}>
                Cancelar
              </Button>
              <Button 
                onClick={handleConfirmResetPassword} 
                disabled={!newPassword || newPassword.length < 6 || resetPasswordMutation.isPending}
              >
                {resetPasswordMutation.isPending ? "Alterando..." : "Confirmar Reset"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </div>


      {/* Busca */}
      <Card className="shadow-sm border-0 bg-card">
        <CardHeader className="pb-3">
          <CardTitle className="text-base font-semibold">Buscar Usuários</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="space-y-2">
            <label className="text-sm font-medium text-foreground">
              Buscar por nome ou email
            </label>
            <div className="relative">
              <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-muted-foreground" />
              <Input
                placeholder="Digite o nome ou email do usuário..."
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                className="pl-10"
              />
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Tabela de Usuários */}
      <Card className="shadow-sm border-0 bg-card">
        <CardHeader>
          <CardTitle className="text-base font-semibold">
            Usuários ({filteredUsuarios.length})
          </CardTitle>
        </CardHeader>
        <CardContent className="p-3 md:p-6 pt-0 md:pt-0">
          {/* Celular: um cartão por pessoa, sem rolar para o lado */}
          <ul className="md:hidden divide-y rounded-md border">
            {filteredUsuarios.map((usuario) => (
              <li key={usuario.id} className="flex items-start gap-3 p-3">
                <div className="min-w-0 flex-1 space-y-1">
                  <p className="font-medium text-foreground leading-snug break-words">{usuario.nome}</p>
                  <p className="flex items-center gap-1 text-xs text-muted-foreground min-w-0">
                    <Mail className="h-3 w-3 shrink-0" /><span className="truncate">{usuario.email}</span>
                  </p>
                  {usuario.telefone && (
                    <p className="flex items-center gap-1 text-xs text-muted-foreground">
                      <Phone className="h-3 w-3 shrink-0" />{usuario.telefone}
                    </p>
                  )}
                  <div className="flex flex-wrap items-center gap-1.5 pt-1">
                    <Badge variant={usuario.ativo ? "default" : "destructive"} className="text-[10px]">{usuario.ativo ? "Ativo" : "Inativo"}</Badge>
                    <Badge variant="outline" className="text-[10px]">{papelDo(usuario)}</Badge>
                    <span className="text-[11px] text-muted-foreground">{usuario.total_demandas} demanda{usuario.total_demandas === 1 ? "" : "s"}</span>
                  </div>
                </div>
                {acoesDoUsuario(usuario)}
              </li>
            ))}
          </ul>

          <div className="hidden md:block rounded-md border overflow-x-auto">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Nome</TableHead>
                  <TableHead>Contato</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead>Papel</TableHead>
                  <TableHead>Demandas</TableHead>
                  <TableHead>Última Atualização</TableHead>
                  <TableHead className="text-right">Ações</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {filteredUsuarios.map((usuario) => (
                  <TableRow key={usuario.id}>
                     <TableCell>
                       <div>
                         <p className="font-medium text-foreground">{usuario.nome}</p>
                         <p className="text-xs text-muted-foreground">
                           Cadastrado em {formatDateTime(usuario.created_at).split(' ')[0]}
                         </p>
                       </div>
                     </TableCell>
                     <TableCell>
                       <div className="space-y-1">
                         <div className="flex items-center gap-1">
                           <Mail className="h-3 w-3 text-muted-foreground" />
                           <span className="text-xs text-foreground">{usuario.email}</span>
                         </div>
                         {usuario.telefone && (
                           <div className="flex items-center gap-1">
                             <Phone className="h-3 w-3 text-muted-foreground" />
                             <span className="text-xs text-foreground">{usuario.telefone}</span>
                           </div>
                         )}
                       </div>
                     </TableCell>
                    <TableCell>
                      <Badge variant={usuario.ativo ? "default" : "destructive"}>
                        {usuario.ativo ? "Ativo" : "Inativo"}
                      </Badge>
                    </TableCell>
                     <TableCell>
                       <div className="flex items-center gap-1">
                         <Shield className="h-3 w-3 text-muted-foreground" />
                         <Badge variant={
                           usuario.role === 'admin' ? 'destructive' : 
                           usuario.role === 'gestor' ? 'default' : 
                           usuario.role === 'atendente' ? 'secondary' : 'outline'
                         }>
                           {usuario.role === 'admin' ? 'Admin' : 
                            usuario.role === 'gestor' ? 'Gestor' :
                            usuario.role === 'atendente' ? 'Atendente' : 'Usuário'}
                         </Badge>
                       </div>
                     </TableCell>
                    <TableCell>
                      <Badge variant="outline">
                        {usuario.total_demandas}
                      </Badge>
                    </TableCell>
                     <TableCell>
                       <span className="text-sm text-foreground">
                         {formatDateTime(usuario.updated_at).split(' ')[0]}
                       </span>
                     </TableCell>
                    <TableCell className="text-right">
                      {acoesDoUsuario(usuario)}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
          
          {filteredUsuarios.length === 0 && (
            <div className="text-center py-8">
              <p className="text-muted-foreground">Nenhum usuário encontrado</p>
            </div>
          )}
        </CardContent>
      </Card>

      <SaidaUsuarioDialog
        usuario={usuarioSaindo}
        pessoas={usuarios.map((u: any) => ({ id: u.id, nome: u.nome, ativo: u.ativo }))}
        onOpenChange={(v) => !v && setUsuarioSaindo(null)}
      />
    </div>
  );
}
